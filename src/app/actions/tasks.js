// ─── Lightweight agent list for task assignment dropdown ────────────────────
export async function fetchAgentsForTaskAssignment() {
  let caller;
  try { caller = await requireUser(); } catch { return { success: false, error: 'Unauthorized' }; }

  const admin = getAdminApp();
  const db = admin.firestore();

  try {
    const snap = await db.collection('agents')
      .where('agency_id', '==', caller.agencyId)
      .get();

    const agents = [];
    snap.forEach(doc => {
      const d = doc.data();
      if (d.status === 'inactive') return;
      agents.push({
        id: doc.id,
        full_name: getDisplayName(d) || d.email || 'Unknown',
        email: d.email || '',
        nxt_id: d.nxt_id || '',
        role: d.role || 'agent',
        hierarchyPath: d.hierarchyPath || '',
      });
    });
    agents.sort((a, b) => (a.full_name || '').localeCompare(b.full_name || ''));
    return { success: true, agents };
  } catch (error) {
    return { success: false, error: error.message };
  }
}

// ─── Fetch tasks ───────────────────────────────────────────────────────────
export async function fetchTasks(hierarchyPath, viewType = 'my', isPrivileged = false) {
  let caller;
  try { caller = await requireUser(); } catch { return { success: false, error: 'Unauthorized' }; }

  const admin = getAdminApp();
  const db = admin.firestore();

  try {
    let query = db.collection('tasks').where('agencyId', '==', caller.agencyId);

    if (viewType === 'my') {
      query = query.where('ownerAgentId', '==', caller.uid);
    }

    const snap = await query.get();
    const tasks = [];

    snap.forEach(doc => {
      const data = doc.data();
      let canSee = false;

      if (data.ownerAgentId === caller.uid) {
        canSee = true;
      } else if (viewType === 'team' && isPrivileged) {
        canSee = true;
      } else if (viewType === 'team' && data.ownerHierarchyPath && hierarchyPath && data.ownerHierarchyPath.startsWith(hierarchyPath + '/')) {
        canSee = true;
      }

      if (canSee) {
        tasks.push({
          id: doc.id,
          ...data,
          dueAt: data.dueAt?.toDate?.()?.toISOString?.() || null,
          completedAt: data.completedAt?.toDate?.()?.toISOString?.() || null,
          createdAt: data.createdAt?.toDate?.()?.toISOString?.() || null,
          updatedAt: data.updatedAt?.toDate?.()?.toISOString?.() || null,
        });
      }
    });

    return { success: true, tasks };
  } catch (error) {
    return { success: false, error: error.message };
  }
}

// ─── Create task ───────────────────────────────────────────────────────────
export async function createTask(data) {
  let caller;
  try { caller = await requireUser(); } catch { return { success: false, error: 'Unauthorized' }; }

  if (isRateLimited(`task-create:${caller.uid}`, 50, 3600000)) {
    return { success: false, error: 'Too many tasks created. Please try again later.' };
  }

  const lengthErr = validateLengths([
    [data.title, 'Title', FIELD_LIMITS.subject],
    [data.description, 'Description', FIELD_LIMITS.description],
  ]);
  if (lengthErr) return { success: false, error: lengthErr };

  const admin = getAdminApp();
  const db = admin.firestore();

  if (!data.title || !data.dueAt) {
    return { success: false, error: 'Title and Due Date are required.' };
  }

  try {
    const ref = db.collection('tasks').doc();
    const dueAtTimestamp = admin.firestore.Timestamp.fromDate(new Date(data.dueAt));

    const taskData = {
      agencyId: caller.agencyId,
      ownerAgentId: data.ownerAgentId || caller.uid,
      ownerAgentName: data.ownerAgentName || null,
      ownerHierarchyPath: data.ownerHierarchyPath || null,
      createdByAgentId: caller.uid,
      createdByAgentName: caller.fullName || null,
      relatedLeadId: data.relatedLeadId || null,
      relatedDealId: data.relatedDealId || null,
      title: data.title,
      description: data.description || null,
      dueAt: dueAtTimestamp,
      priority: data.priority || 'medium',
      status: 'open',
      completedAt: null,
      autoGenerated: data.autoGenerated || false,
      sourceTemplateId: data.sourceTemplateId || null,
      createdAt: admin.firestore.FieldValue.serverTimestamp(),
      updatedAt: admin.firestore.FieldValue.serverTimestamp()
    };

    await ref.set(taskData);

    return { success: true, id: ref.id };
  } catch (error) {
    return { success: false, error: error.message };
  }
}

// ─── Send work authorization task to all active agents ────────────────────
export async function sendWorkAuthorizationTasks() {
  let caller;
  try { caller = await requireAdmin(); } catch { return { success: false, error: 'Unauthorized' }; }

  const admin = getAdminApp();
  const db = admin.firestore();

  try {
    const snap = await db.collection('agents')
      .where('agency_id', '==', caller.agencyId)
      .where('status', '==', 'active')
      .get();

    if (snap.empty) return { success: true, sent: 0 };

    // Filter out agents who already have work_authorization on file
    const agentsNeedingTask = [];
    snap.forEach(doc => {
      const data = doc.data();
      if (!data.qualification?.work_authorization) {
        agentsNeedingTask.push({ id: doc.id, ...data });
      }
    });

    if (agentsNeedingTask.length === 0) return { success: true, sent: 0, message: 'All agents already have work authorization on file.' };

    const dueDate = new Date();
    dueDate.setDate(dueDate.getDate() + 7);
    const dueAtTimestamp = admin.firestore.Timestamp.fromDate(dueDate);

    const batch = db.batch();
    for (const agent of agentsNeedingTask) {
      const ref = db.collection('tasks').doc();
      batch.set(ref, {
        agencyId: caller.agencyId,
        ownerAgentId: agent.id,
        ownerAgentName: getDisplayName(agent) || agent.email || 'Unknown',
        ownerHierarchyPath: agent.hierarchyPath || null,
        createdByAgentId: caller.uid,
        createdByAgentName: caller.fullName || null,
        title: 'Update Work Authorization Status',
        description: 'Please update your work authorization status. Go to your Profile and select one of the following:\n\n• U.S. Citizen\n• U.S. Permanent Resident (Green Card)\n• Employment Authorization Document (EAD)\n• Employment Visa (H-1B or other work-authorized visa)\n• Other valid work authorization\n• Not currently authorized to work in the United States\n\nThis is required for compliance records.',
        dueAt: dueAtTimestamp,
        priority: 'high',
        status: 'open',
        completedAt: null,
        autoGenerated: true,
        sourceTemplateId: 'work-authorization-compliance',
        createdAt: admin.firestore.FieldValue.serverTimestamp(),
        updatedAt: admin.firestore.FieldValue.serverTimestamp(),
      });
    }
    await batch.commit();

    return { success: true, sent: agentsNeedingTask.length };
  } catch (error) {
    return { success: false, error: error.message };
  }
}

// ─── Update task status ────────────────────────────────────────────────────
export async function updateTaskStatus(taskId, status) {
  let caller;
  try { caller = await requireUser(); } catch { return { success: false, error: 'Unauthorized' }; }

  const admin = getAdminApp();
  const db = admin.firestore();

  try {
    await db.runTransaction(async (transaction) => {
      const taskRef = db.collection('tasks').doc(taskId);
      const taskSnap = await transaction.get(taskRef);

      if (!taskSnap.exists) throw new Error("Task not found");
      const currentTask = taskSnap.data();

      // Verify the task belongs to the caller's agency
      if (currentTask.agencyId !== caller.agencyId) throw new Error("Task not found");

      // Only task owner or admin can update status
      const isAdmin = caller.isOwner || caller.role === 'admin' || caller.role === 'it_engineer';
      if (currentTask.ownerAgentId !== caller.uid && !isAdmin) {
        throw new Error("Not authorized to update this task");
      }

      if (currentTask.status !== status) {
        transaction.update(taskRef, {
          status,
          completedAt: status === 'completed' ? admin.firestore.FieldValue.serverTimestamp() : null,
          updatedAt: admin.firestore.FieldValue.serverTimestamp()
        });

        if (status === 'completed') {
          incrementAgentMetrics(transaction, admin, db, currentTask.agencyId, currentTask.ownerAgentId, currentTask.ownerHierarchyPath, {
            tasksCompletedCount: 1
          });
        } else if (currentTask.status === 'completed' && status === 'open') {
          incrementAgentMetrics(transaction, admin, db, currentTask.agencyId, currentTask.ownerAgentId, currentTask.ownerHierarchyPath, {
            tasksCompletedCount: -1
          });
        }
      }
    });
    return { success: true };
  } catch (error) {
    return { success: false, error: error.message };
  }
}

// ─── Update task details (title, description, priority, dueAt) ─────────────
export async function updateTaskDetails(taskId, updates) {
  let caller;
  try { caller = await requireUser(); } catch { return { success: false, error: 'Unauthorized' }; }

  if (!taskId) return { success: false, error: 'No task ID' };
  const admin = getAdminApp();
  const db = admin.firestore();

  // Verify the task belongs to the caller's agency and they own it or are admin
  try {
    const taskSnap = await db.collection('tasks').doc(taskId).get();
    if (!taskSnap.exists || taskSnap.data().agencyId !== caller.agencyId) {
      return { success: false, error: 'Task not found.' };
    }
    const isAdmin = caller.isOwner || caller.role === 'admin' || caller.role === 'it_engineer';
    if (taskSnap.data().ownerAgentId !== caller.uid && !isAdmin) {
      return { success: false, error: 'Not authorized to update this task.' };
    }
  } catch (error) {
    return { success: false, error: error.message };
  }

  const allowed = ['title', 'description', 'priority', 'dueAt'];
  const clean = {};
  for (const key of allowed) {
    if (updates[key] !== undefined) clean[key] = updates[key];
  }
  clean.updatedAt = admin.firestore.FieldValue.serverTimestamp();

  try {
    await db.collection('tasks').doc(taskId).update(clean);
    return { success: true };
  } catch (error) {
    return { success: false, error: error.message };
  }
}

