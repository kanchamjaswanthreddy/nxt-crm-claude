export async function createOrUpdateTemplate(data) {
  let caller;
  try { caller = await requireAdmin(); } catch { return { success: false, error: 'Unauthorized' }; }

  const admin = getAdminApp();
  const db = admin.firestore();

  try {
    let ref;
    const templateData = {
      agencyId: caller.agencyId,
      triggerStageId: data.triggerStageId,
      taskTitle: data.taskTitle,
      daysUntilDue: Number(data.daysUntilDue),
      priority: data.priority,
      active: data.active,
      updatedAt: admin.firestore.FieldValue.serverTimestamp()
    };

    if (data.id) {
      ref = db.collection('stageTaskTemplates').doc(data.id);
      await ref.update(templateData);
    } else {
      ref = db.collection('stageTaskTemplates').doc();
      templateData.createdAt = admin.firestore.FieldValue.serverTimestamp();
      await ref.set(templateData);
    }

    return { success: true, id: ref.id };
  } catch (error) {
    return { success: false, error: error.message };
  }
}
